ALTER TABLE TM_LOGS ADD CONSTRAINT FK_TL_RESULT FOREIGN KEY (RESULT) REFERENCES TM_RESULT_CODES(RESULT_CODE);

ALTER TABLE TM_LOGS DROP COLUMN SUB_REASON;
ALTER TABLE TM_LOGS ADD SUB_REASON VARCHAR2(30 CHAR);
ALTER TABLE TM_LOGS ADD CONSTRAINT FK_TL_SUB_REASON FOREIGN KEY (RESULT, SUB_REASON) REFERENCES TM_SUB_REASON_CODES(RESULT_CODE, SUB_CODE);

COMMENT ON COLUMN TM_LOGS.RESULT     IS 'TM_RESULT_CODES.RESULT_CODE 참조 (예: NO_ANSWER) — 예전엔 한글 자유텍스트였음';
COMMENT ON COLUMN TM_LOGS.SUB_REASON IS 'TM_SUB_REASON_CODES.SUB_CODE 참조 (예: ENV_UNFIT). UNFIT/REJECT/INVALID에서만 씀';

