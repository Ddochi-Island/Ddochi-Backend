-- ================================================================
-- 10_tm_result_codes.sql — TM_LOGS 결과/사유 코드 마스터 (신규)
-- ================================================================
-- TM_LOGS.RESULT/SUB_REASON을 한글 자유 텍스트 대신 코드값으로 저장하기 위한
-- 참조 테이블 — POSITION_CODES(06_members.sql)와 같은 CODE/LABEL 마스터
-- 테이블 패턴. 대화 중 정리한 "대분류(단계)/중분류(결과유형)/소분류(세부사유)"
-- 체계 중, 실제로 결과를 저장하는 코드가 있는 TM 단계만 우선 적용함 — 번찾
-- 반려(shed_pending_reject)는 사유를 아예 안 받고, 매칭(update_match)은
-- 아직 501 스텁이라 저장할 곳 자체가 없어서 이번엔 대상에서 뺌.
-- ================================================================

CREATE TABLE TM_RESULT_CODES (
  RESULT_CODE   VARCHAR2(20 CHAR)            PRIMARY KEY,
  LABEL         VARCHAR2(30 CHAR)            NOT NULL,
  SORT_ORDER    NUMBER(3)                    NOT NULL
);

COMMENT ON TABLE TM_RESULT_CODES IS 'TM_LOGS.RESULT 코드 마스터(중분류) — 부재중/예약티엠/만남픽스/비합/거절/무효';

