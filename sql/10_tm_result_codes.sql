CREATE TABLE TM_SUB_REASON_CODES (
  RESULT_CODE   VARCHAR2(20 CHAR)            NOT NULL,
  SUB_CODE      VARCHAR2(30 CHAR)            NOT NULL,
  LABEL         VARCHAR2(30 CHAR)            NOT NULL,
  SORT_ORDER    NUMBER(3)                    NOT NULL,
  CONSTRAINT PK_TM_SUB_REASON_CODES PRIMARY KEY (RESULT_CODE, SUB_CODE),
  CONSTRAINT FK_TSRC_RESULT FOREIGN KEY (RESULT_CODE) REFERENCES TM_RESULT_CODES(RESULT_CODE)
);

COMMENT ON TABLE TM_SUB_REASON_CODES IS 'TM_LOGS.SUB_REASON 코드 마스터(소분류) — 비합/거절/무효에만 존재. (RESULT_CODE, SUB_CODE) 복합키라 같은 개념(예: 환경)도 결과별로 독립적으로 존재 가능';

