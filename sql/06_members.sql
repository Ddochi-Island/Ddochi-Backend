-- ================================================================
-- 06_members.sql — Members & RBAC 도메인 (재설계, USERS/ROLES/AUTH_CONFIGS 대체)
-- ================================================================
-- schema-spec.md(CRM Database Schema Specification, Member & Daily Report
-- Domain)의 "3. Member & RBAC Domain"을 그대로 구현.
--
-- USERS.ROLE_IDS(JSON 배열 컬럼)를 MEMBER_POSITION_MAPPINGS N:M 조인테이블로,
-- USERS.TEAM_ID/AREA_ID(현재값만)를 MEMBER_AFFILIATION_HISTORIES(이력 추적)로
-- 대체 — 스펙 원문 그대로. 생성 순서는 의존관계 순(POSITION_CODES가 먼저,
-- MEMBERS가 그다음, 나머지는 그 뒤).
--
-- 스펙에 없지만 실제 로그인 로직(auth.py)이 쓰는 필드 3개(GMAIL/TELEGRAM_ID/
-- GOALS)는 회원 1명당 값 하나인 단순 속성이라 MEMBERS에 직접 추가.
-- 감사컬럼(CREATED_AT 등)은 스펙엔 없지만 이 프로젝트의 기존 테이블 전체가
-- 따르는 관례라 동일하게 유지.
-- ================================================================

CREATE TABLE POSITION_CODES (
  POSITION_CODE   VARCHAR2(50 CHAR)            PRIMARY KEY,
  POSITION_NAME   VARCHAR2(50 CHAR)            NOT NULL,
  PERMISSIONS     CLOB                         NOT NULL,
  DESCRIPTION     VARCHAR2(255 CHAR),
  CREATED_AT      TIMESTAMP(6) WITH TIME ZONE  DEFAULT SYSTIMESTAMP NOT NULL,
  UPDATED_AT      TIMESTAMP(6) WITH TIME ZONE  DEFAULT SYSTIMESTAMP NOT NULL,
  CREATED_BY      VARCHAR2(20 CHAR)            NOT NULL,
  UPDATED_BY      VARCHAR2(20 CHAR)            NOT NULL,
  DELETED_AT      TIMESTAMP(6) WITH TIME ZONE,
  CONSTRAINT CK_PC_PERMS_JSON CHECK (PERMISSIONS IS JSON)
);

COMMENT ON TABLE  POSITION_CODES             IS '직책 마스터. 기존 ROLES 대체';
COMMENT ON COLUMN POSITION_CODES.PERMISSIONS IS 'JSON 배열. 예: ["admin","region_staff"]. 인가 판정의 실제 근거';

CREATE TABLE MEMBERS (
  MEMBER_ID       VARCHAR2(50 CHAR)            PRIMARY KEY,
  NAME            VARCHAR2(50 CHAR)            NOT NULL,
  STATUS          VARCHAR2(20 CHAR)            DEFAULT 'ACTIVE' NOT NULL
                  CHECK (STATUS IN ('ACTIVE','INACTIVE','LEAVE')),
  GMAIL           VARCHAR2(255 CHAR),
  TELEGRAM_ID     VARCHAR2(20 CHAR),
  GOALS           CLOB                         CHECK (GOALS IS NULL OR GOALS IS JSON),
  CREATED_AT      TIMESTAMP(6) WITH TIME ZONE  DEFAULT SYSTIMESTAMP NOT NULL,
  UPDATED_AT      TIMESTAMP(6) WITH TIME ZONE  DEFAULT SYSTIMESTAMP NOT NULL,
  CREATED_BY      VARCHAR2(20 CHAR)            NOT NULL,
  UPDATED_BY      VARCHAR2(20 CHAR)            NOT NULL,
  DELETED_AT      TIMESTAMP(6) WITH TIME ZONE
);

CREATE UNIQUE INDEX UX_MEMBERS_TG ON MEMBERS (
  CASE WHEN TELEGRAM_ID IS NOT NULL THEN TELEGRAM_ID END
);

COMMENT ON TABLE  MEMBERS             IS '지역원 마스터. 기존 USERS 대체 — TEAM_ID/AREA_ID는 MEMBER_AFFILIATION_HISTORIES로, ROLE_IDS는 MEMBER_POSITION_MAPPINGS로 분리';
COMMENT ON COLUMN MEMBERS.MEMBER_ID   IS 'PK. 사번 형식 (예: ''00410926-01700'')';
COMMENT ON COLUMN MEMBERS.GOALS       IS '개인 목표 JSON. 기존 USERS.GOALS와 동일 형식';

CREATE TABLE MEMBER_POSITION_MAPPINGS (
  MAPPING_ID      NUMBER(19)                   GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  MEMBER_ID       VARCHAR2(50 CHAR)            NOT NULL,
  POSITION_CODE   VARCHAR2(50 CHAR)            NOT NULL,
  ASSIGNED_AT     DATE,
  CONSTRAINT FK_MPM_MEMBER   FOREIGN KEY (MEMBER_ID)     REFERENCES MEMBERS(MEMBER_ID),
  CONSTRAINT FK_MPM_POSITION FOREIGN KEY (POSITION_CODE) REFERENCES POSITION_CODES(POSITION_CODE)
);

CREATE INDEX IX_MPM_MEMBER ON MEMBER_POSITION_MAPPINGS (MEMBER_ID);

COMMENT ON TABLE MEMBER_POSITION_MAPPINGS IS '회원-직책 N:M. 기존 USERS.ROLE_IDS(JSON 배열) 대체 — 겸임 지원';

CREATE TABLE MEMBER_AFFILIATION_HISTORIES (
  AFFILIATION_ID  NUMBER(19)                   GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  MEMBER_ID       VARCHAR2(50 CHAR)            NOT NULL,
  REGION_CODE     VARCHAR2(50 CHAR)            NOT NULL,
  DISTRICT_CODE   VARCHAR2(50 CHAR)            NOT NULL,
  START_DATE      DATE                         NOT NULL,
  END_DATE        DATE,
  IS_CURRENT      NUMBER(1)                    DEFAULT 1 NOT NULL CHECK (IS_CURRENT IN (0,1)),
  CONSTRAINT FK_MAH_MEMBER FOREIGN KEY (MEMBER_ID) REFERENCES MEMBERS(MEMBER_ID)
);

CREATE INDEX IX_MAH_MEMBER_CURRENT ON MEMBER_AFFILIATION_HISTORIES (
  MEMBER_ID, CASE WHEN IS_CURRENT = 1 THEN 1 END
);

COMMENT ON TABLE MEMBER_AFFILIATION_HISTORIES IS '회원 소속(지역/구역) 변경 이력. 기존 USERS.TEAM_ID/AREA_ID(현재값만) 대체 — 시점별 소속 추적 가능';

COMMIT;
