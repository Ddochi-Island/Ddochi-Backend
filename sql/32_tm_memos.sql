-- 합당한자 통화 메모 — 댓글처럼 한 줄씩(작성 시각·작성자·내용). 전도팀장 이하는 자기 메모만 수정·삭제
CREATE TABLE SARANG_TM_MEMOS (
  MEMO_ID           VARCHAR2(32 CHAR)            PRIMARY KEY,
  SARANG_ID         VARCHAR2(50 CHAR)            NOT NULL,
  AUTHOR_MEMBER_ID  VARCHAR2(50 CHAR)            NOT NULL,
  CONTENT           VARCHAR2(2000 CHAR)          NOT NULL,
  CREATED_AT        TIMESTAMP(6) WITH TIME ZONE  DEFAULT SYSTIMESTAMP NOT NULL,
  UPDATED_AT        TIMESTAMP(6) WITH TIME ZONE,
  DELETED_AT        TIMESTAMP(6) WITH TIME ZONE,
  CONSTRAINT FK_TM_MEMO_SARANG FOREIGN KEY (SARANG_ID) REFERENCES SARANG(SARANG_ID),
  CONSTRAINT FK_TM_MEMO_AUTHOR FOREIGN KEY (AUTHOR_MEMBER_ID) REFERENCES MEMBERS(MEMBER_ID)
);

CREATE INDEX IX_TM_MEMO_SARANG ON SARANG_TM_MEMOS (SARANG_ID);
