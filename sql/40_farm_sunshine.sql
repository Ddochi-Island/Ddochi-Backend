-- 밭 게임 햇살(재화) 적립·사용 이력 — 잔액은 SUM(AMOUNT)(사용은 음수 행). 같은 보상은 (회원, 사유, 대상) 유니크로 한 번만
CREATE TABLE FARM_SUNSHINE_LOG (
  LOG_ID      VARCHAR2(32 CHAR)            PRIMARY KEY,
  MEMBER_ID   VARCHAR2(50 CHAR)            NOT NULL,
  REASON      VARCHAR2(40 CHAR)            NOT NULL,
  REF_ID      VARCHAR2(64 CHAR)            NOT NULL,
  AMOUNT      NUMBER(10)                   NOT NULL,
  CREATED_AT  TIMESTAMP(6) WITH TIME ZONE  DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT FK_FARM_SUN_MEMBER FOREIGN KEY (MEMBER_ID) REFERENCES MEMBERS(MEMBER_ID),
  CONSTRAINT UQ_FARM_SUNSHINE UNIQUE (MEMBER_ID, REASON, REF_ID)
);
