-- SARANG_MATCH_HISTORIES.RESULT/SUB_REASON을 한글 자유 텍스트 대신 코드값으로
-- 저장 — 10_tm_result_codes.sql과 동일한 CODE/LABEL 마스터 패턴(TM_RESULT_CODES/
-- TM_SUB_REASON_CODES)을 매칭 결과에도 적용.
--
-- LABEL은 MatchingScreen.vue(레거시 프론트, 안 건드림)가 문자열 그대로 비교하는
-- 값과 1:1로 맞춤 — '2차 만남'/'상담 따기'는 다른 코드들과 달리 스페이스 없는
-- '2차만남'/'상담따기'로 저장(프론트가 resDisp.includes('상담따기') 같은 무공백
-- 부분일치로 체크하기 때문. 04_prospects.sql류의 다른 화면엔 안 쓰여서 문제 없음).
-- ================================================================

CREATE TABLE MATCH_RESULT_CODES (
  RESULT_CODE   VARCHAR2(20 CHAR)            PRIMARY KEY,
  LABEL         VARCHAR2(30 CHAR)            NOT NULL,
  SORT_ORDER    NUMBER(3)                    NOT NULL
);

COMMENT ON TABLE MATCH_RESULT_CODES IS 'SARANG_MATCH_HISTORIES.RESULT 코드 마스터 — 취소/밀림/비합/탈락/2차만남/상담따기';

