CREATE TABLE MATCH_SUB_REASON_CODES (
  RESULT_CODE   VARCHAR2(20 CHAR)            NOT NULL,
  SUB_CODE      VARCHAR2(30 CHAR)            NOT NULL,
  LABEL         VARCHAR2(30 CHAR)            NOT NULL,
  SORT_ORDER    NUMBER(3)                    NOT NULL,
  CONSTRAINT PK_MSRC_SUB_REASON PRIMARY KEY (RESULT_CODE, SUB_CODE),
  CONSTRAINT FK_MSRC_RESULT FOREIGN KEY (RESULT_CODE) REFERENCES MATCH_RESULT_CODES(RESULT_CODE)
);

COMMENT ON TABLE MATCH_SUB_REASON_CODES IS 'SARANG_MATCH_HISTORIES.SUB_REASON 코드 마스터 — 취소/비합/탈락에만 존재(밀림/2차만남/상담따기는 세부사유 없음)';

